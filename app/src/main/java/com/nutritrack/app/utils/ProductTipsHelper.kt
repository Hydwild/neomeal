package com.nutritrack.app.utils

object ProductTipsHelper {

    // Автоматические советы по имени/категории продукта
    fun getAutoTip(name: String, category: String): String? {
        val nameLower = name.lowercase()

        // Проблемы с желудком
        val stomachBad = listOf(
            "острые", "перец", "чили", "чеснок", "лук", "уксус",
            "кетчуп", "горчица", "газированная", "кола", "алкоголь",
            "кофе", "капуста", "фасоль", "горох", "бобы", "редис"
        )
        val stomachGood = listOf(
            "овсянка", "банан", "рис", "гречка", "творог", "йогурт",
            "кефир", "варёный", "паровой", "тыква", "морковь", "картофель"
        )

        // Набор массы
        val gainMass = listOf(
            "говядина", "курица", "индейка", "лосось", "тунец", "яйцо",
            "творог", "орехи", "арахис", "авокадо", "рис", "гречка",
            "овсянка", "банан"
        )

        // Похудение
        val weightLoss = listOf(
            "огурец", "помидор", "шпинат", "брокколи", "сельдерей",
            "греческий йогурт", "грейпфрут", "яблоко", "зелёный чай"
        )

        // Нежелательно при похудении
        val badForLoss = listOf(
            "шоколад", "торт", "печенье", "сахар", "мёд", "мороженое",
            "майонез", "масло", "фаст-фуд", "чипсы", "фри"
        )

        val tips = mutableListOf<String>()

        // Желудок — нежелательно
        if (stomachBad.any { nameLower.contains(it) }) {
            tips.add("⚠️ Нежелательно при проблемах с желудком")
        }
        // Желудок — хорошо
        if (stomachGood.any { nameLower.contains(it) }) {
            tips.add("✅ Подходит при чувствительном желудке")
        }
        // Набор массы
        if (gainMass.any { nameLower.contains(it) }) {
            tips.add("💪 Отлично для набора мышечной массы")
        }
        // Похудение
        if (weightLoss.any { nameLower.contains(it) }) {
            tips.add("🔥 Помогает при похудении")
        }
        // Плохо для похудения
        if (badForLoss.any { nameLower.contains(it) }) {
            tips.add("❌ Нежелательно при похудении")
        }

        // По категории
        when (category.lowercase()) {
            "мясо" -> tips.add("💪 Источник белка для мышц")
            "рыба" -> tips.add("🐟 Содержит омега-3 жирные кислоты")
            "молочные" -> tips.add("🦴 Источник кальция для костей")
            "фрукты" -> tips.add("🍎 Богато витаминами и клетчаткой")
            "овощи" -> tips.add("🥦 Низкокалорийный источник витаминов")
            "крупы" -> tips.add("⚡ Долгие углеводы — энергия на весь день")
            "напитки" -> if (nameLower.contains("сок") || nameLower.contains("газ")) {
                tips.add("⚠️ Содержит сахар — пей умеренно")
            }
            "сладкое" -> tips.add("🍬 Ограничь при снижении веса")
            "орехи" -> tips.add("🥜 Полезные жиры, но калорийны")
        }

        return tips.firstOrNull()
    }

    // Все советы для продукта (для детального просмотра)
    fun getAllTips(name: String): List<String> {
        val nameLower = name.lowercase()
        val tips = mutableListOf<String>()

        val rules = mapOf(
            listOf("острые", "перец", "чили", "горчица", "уксус") to
                    "⚠️ Раздражает слизистую желудка — ограничь при гастрите",
            listOf("говядина", "курица", "индейка", "лосось", "тунец") to
                    "💪 Высокобелковый продукт — идеален для роста мышц",
            listOf("овсянка", "гречка", "рис") to
                    "⚡ Медленные углеводы — даёт энергию на 3–4 часа",
            listOf("шоколад", "торт", "сахар", "мёд") to
                    "🍬 Высокий гликемический индекс — вызывает скачок сахара",
            listOf("лосось", "тунец", "скумбрия") to
                    "🐟 Богат омега-3 — полезен для сердца и суставов",
            listOf("банан") to
                    "🍌 Отлично есть перед тренировкой — быстрая энергия",
            listOf("творог", "яйцо") to
                    "🌙 Хорошо есть перед сном — медленный протеин",
            listOf("кофе") to
                    "☕ Может повышать давление и кислотность желудка",
            listOf("молоко", "йогурт", "кефир") to
                    "🦴 Источник кальция и пробиотиков",
            listOf("орехи", "миндаль", "грецкий") to
                    "🥜 Богат полезными жирами и магнием, но очень калориен",
            listOf("брокколи", "шпинат", "огурец") to
                    "🥗 Отличен для похудения — мало калорий, много клетчатки"
        )

        rules.forEach { (keywords, tip) ->
            if (keywords.any { nameLower.contains(it) }) tips.add(tip)
        }

        return tips.ifEmpty { listOf("ℹ️ Нет автоматических советов для этого продукта") }
    }
}